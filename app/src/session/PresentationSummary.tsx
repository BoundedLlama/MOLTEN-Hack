import { useEffect, useRef, useState } from 'react'
import { formatTime } from './SessionClock'
import { coaching, type HeadSummary, type HeadInterval } from './headSummary'

export default function PresentationSummary({ summary, timeline, onClose }: { summary: HeadSummary; timeline: HeadInterval[]; onClose: () => void }) {
  const [aiText, setAiText] = useState('')
  const [aiError, setAiError] = useState('')
  const [attempt, setAttempt] = useState(0)
  useEffect(() => {
    if (summary.audiencePercent === null) return
    const controller = new AbortController()
    void fetch('/api/presentation-summary', {
      method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(summary), signal: AbortSignal.any([controller.signal, AbortSignal.timeout(25000)]),
    }).then(async response => {
      const data = await response.json()
      if (!response.ok) throw new Error(data.error || 'AI coaching is unavailable.')
      if (typeof data.summary !== 'string' || !data.summary.trim()) throw new Error('AI coaching returned an empty summary.')
      if (!controller.signal.aborted) setAiText(data.summary)
    }).catch(error => {
      if (!controller.signal.aborted) setAiError(error instanceof Error && !error.message.includes('JSON') ? error.message : 'AI coaching is unavailable on this server.')
    })
    return () => controller.abort()
  }, [summary, attempt])
  const close = useRef<HTMLButtonElement>(null)
  useEffect(() => { close.current?.focus({ preventScroll: true }) }, [])
  const seconds = (ms: number) => `${(ms / 1000).toFixed(1)}s`
  return <section className="presentation-summary" aria-label="Presentation summary">
    <div className="summary-card">
      <span className="vr-eyebrow">PRACTICE COMPLETE</span>
      <h2>Your presentation, reflected.</h2>
      <p>Total presentation time <strong>{formatTime(summary.durationMs)}</strong> · Pauses excluded</p>
      <div className="summary-stats">
        <div><strong>{summary.audiencePercent === null ? '—' : `${summary.audiencePercent}%`}</strong><span>Facing audience · {seconds(summary.audienceMs)}</span></div>
        <div><strong>{summary.audiencePercent === null ? '—' : `${100 - summary.audiencePercent}%`}</strong><span>Facing board · {seconds(summary.boardMs)}</span></div>
      </div>
      {summary.audiencePercent !== null && <div className="summary-bar" aria-hidden="true"><span style={{ width: `${summary.audiencePercent}%` }} /></div>}
      <p>Longest board-facing stretch: <strong>{seconds(summary.longestBoardMs)}</strong><br />Returns to the audience: <strong>{summary.returns}</strong></p>
      {summary.durationMs > 0 && <figure className="summary-timeline">
        <figcaption>Head direction throughout your presentation</figcaption>
        <div className="summary-timeline-track" role="img" aria-label="Timeline from start to finish. Green indicates audience, gold indicates board, and gray indicates untracked time.">
          {timeline.map(interval => <span key={interval.startMs} className={`zone-${interval.zone ?? 'unknown'}`}
            style={{ width: `${100 * (interval.endMs - interval.startMs) / summary.durationMs}%` }}
            title={`${formatTime(interval.startMs)}–${formatTime(interval.endMs)}: ${interval.zone ?? 'untracked'}`} />)}
        </div>
        <div className="summary-timeline-labels"><span>Start · 00:00</span><span>{formatTime(summary.durationMs)} · Finish</span></div>
        <div className="summary-legend"><span>● Audience</span><span>● Board</span><span>● Untracked</span></div>
      </figure>}
      <div className="summary-coaching" aria-live="polite">
        <h3>{aiText ? 'AI presentation coach' : 'Personalized coaching'}</h3>
        <p style={{ whiteSpace: 'pre-line' }}>{aiText || coaching(summary)}</p>
        <small>{aiText ? 'Generated by AI via AssemblyAI from your session measurements.' : 'Local feedback based on your session measurements.'}</small>
        {!aiText && !aiError && summary.audiencePercent !== null && <p role="status">Writing your AI summary…</p>}
        {aiError && <><p role="status">{aiError}</p><button onClick={() => { setAiError(''); setAttempt(value => value + 1) }}>Retry AI summary</button></>}
      </div>
      <p className="summary-note">Head orientation is a practice cue, not a measurement of eye contact. Percentages use recorded time. Untracked time: {seconds(summary.untrackedMs)}.</p>
      {summary.previewMs > 0 && <p className="summary-note">Desktop simulation: {seconds(summary.previewMs)} reflects camera movement, not physical head tracking.{summary.headsetMs > 0 && ` Headset tracking: ${seconds(summary.headsetMs)}.`}</p>}
      <button ref={close} className="primary" onClick={onClose}>Back to practice</button>
    </div>
  </section>
}
